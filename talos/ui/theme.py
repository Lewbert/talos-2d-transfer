def apply_theme(app: QApplication) -> None:
    app.setStyle("Fusion")
    palette = QPalette()
    palette.setColor(QPalette.ColorRole.Window, QColor(BG))
    palette.setColor(QPalette.ColorRole.WindowText, QColor(TEXT))
    palette.setColor(QPalette.ColorRole.Base, QColor(BG))
    palette.setColor(QPalette.ColorRole.AlternateBase, QColor(PANEL))
    palette.setColor(QPalette.ColorRole.Text, QColor(TEXT))
    palette.setColor(QPalette.ColorRole.Button, QColor(PANEL_ALT))
    palette.setColor(QPalette.ColorRole.ButtonText, QColor(TEXT))
    palette.setColor(QPalette.ColorRole.Highlight, QColor(ACCENT_DARK))
    palette.setColor(QPalette.ColorRole.HighlightedText, QColor("#ffffff"))
    palette.setColor(QPalette.ColorRole.PlaceholderText, QColor(TEXT_DIM))
    app.setPalette(palette)
    global _current_font_size
    _current_font_size = _DEFAULT_FONT_SIZE
    app.setStyleSheet(build_qss())


def set_font_size(app: QApplication, px: int) -> None:
    """Re-apply the stylesheet at a new base font size (live re-theme)."""
    global _current_font_size
    _current_font_size = max(8, min(int(px), 16))
    app.setStyleSheet(build_qss(_current_font_size, ACCENT, ACCENT_DARK))


def set_accent(app: QApplication, accent_hex: str,
               accent_dark: str | None = None) -> str:
    """Apply an accent color live (validated). Returns the applied hex,
    or the current ACCENT when the input is invalid."""
    global ACCENT, ACCENT_DARK
    color = QColor(accent_hex)
    if not color.isValid():
        return ACCENT
    ACCENT = color.name()
    ACCENT_DARK = accent_dark or accent_dark_for(ACCENT)
    palette = app.palette()
    palette.setColor(QPalette.ColorRole.Highlight, QColor(ACCENT_DARK))
    app.setPalette(palette)
    app.setStyleSheet(build_qss(_current_font_size, ACCENT, ACCENT_DARK))
    return ACCENT

ACCENT_GROUPS = (
    ("Endfield", ("Endfield", "Valley IV", "Wuling")),
    ("Warhammer", ("Khorne", "Tzeentch", "Nurgle", "Slaanesh")),
)


def accent_dark_for(accent_hex: str) -> str:
    """The paired dark for a preset match, else a fixed darken factor."""
    for _name, accent, dark in ACCENT_PRESETS:
        if accent_hex.strip().lower() == accent.lower():
            return dark
    color = QColor(accent_hex)
    return color.darker(140).name() if color.isValid() else ACCENT_DARK



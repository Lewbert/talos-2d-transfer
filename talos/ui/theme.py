"""Dark professional theme: Fusion style + QSS (Blender/VSCode-flavored).

The QSS is built per font size via ``build_qss`` — ``apply_theme`` uses
the default, ``set_font_size`` re-applies live (Preferences → General).

Rules of thumb kept here:
- No universal ``QWidget { background }`` — the QPalette Window role
  paints plain widgets; explicit backgrounds only where panels need to
  differ from the base (the old universal rule caused dark rectangles
  behind every label).
- ``QGroupBox::title`` needs ``background: transparent`` (the classic
  square-patch artifact otherwise).
- Widgets that need a themed look carry an objectName (``#danger``,
  ``#readout``, ``#dim``, ``#ok``, ``#mode_badge``, ``#log``, …) —
  inline ``setStyleSheet`` calls with hardcoded colors are banned.
"""

